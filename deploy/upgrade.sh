#!/usr/bin/env bash
# ==============================================================================
# Crypto AI Quantitative Trading - 零中斷安全升級腳本 (Pre-Flight Test & Safe Switch)
# ==============================================================================
# 機制保證：
# 1. 執行 git pull 取得最新代碼
# 2. 自動在「隔離臨時容器」中執行全套 120 項自動化測試
# 3. 測試 100% 通過 -> 才觸發 docker compose up -d --build (2 秒平滑熱切換)
# 4. 若有任何一項測試失敗 -> 立即中斷 (Abort)，現正運行的所有實盤容器絕不受干擾！
# ==============================================================================

set -e

echo "=========================================================="
echo "  [1/3] 拉取 GitHub 遠端最新代碼..."
echo "=========================================================="
git pull

echo "=========================================================="
echo "  [2/3] 執行升級預檢測試 (Pre-Flight Verification)..."
echo "=========================================================="
echo "正在臨時隔離容器中驗證全套 120 項策略與風控測試..."

if docker compose run --rm --no-deps swap_3x pytest tests/ -q; then
    echo ""
    echo "✅ 預檢測試 100% 通過！新代碼驗證安全無虞。"
else
    echo ""
    echo "❌ 預檢測試未通過！立即中斷 (ABORT) 升級流程！"
    echo "🛡️  安全保護生效：目前正在執行的實盤交易機器人持續運行，完全未受影響。"
    exit 1
fi

echo "=========================================================="
echo "  [3/3] 執行零中斷平滑熱重啟 (Hot Cutover)..."
echo "=========================================================="
docker compose up -d --build

echo ""
echo "=========================================================="
echo "  🎉 升級成功！所有機器人、排程器與即時看板已更新並持續守護。"
echo "=========================================================="
